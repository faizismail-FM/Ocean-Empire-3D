import { z } from "zod";
import type { GameDate } from "./calendar";
import { GameModeSchema, PortAccessSchema, PortInfrastructureKindSchema } from "@/data/schemas";

/**
 * Mutable player state. Kept deliberately separate from the immutable reference data in
 * `src/data`. Everything here is serialisable and validated with Zod when a save is loaded
 * so that corrupted or outdated saves fail gracefully instead of crashing the game.
 */

export const SAVE_VERSION = 1;

export const GameDateSchema = z.object({ year: z.number().int(), month: z.number().int(), day: z.number().int() });

export const GeoPointSchema = z.object({ lat: z.number(), lon: z.number() });

export const WaypointSchema = z.object({
  lat: z.number(),
  lon: z.number(),
  label: z.string().optional(),
  port_id: z.string().optional(),
});
export type Waypoint = z.infer<typeof WaypointSchema>;

export const CargoItemSchema = z.object({
  good_id: z.string(),
  quantity: z.number(),
  contract_id: z.string().nullable(),
  /** Purchase price per unit for market cargo, used for profit reporting. */
  bought_at: z.number().nullable(),
});
export type CargoItem = z.infer<typeof CargoItemSchema>;

export const ShipStatusSchema = z.enum(["docked", "sailing", "drifting"]);
export type ShipStatus = z.infer<typeof ShipStatusSchema>;

export const ActiveVoyageSchema = z.object({
  origin_port_id: z.string(),
  destination_port_id: z.string(),
  departed_sim_seconds: z.number(),
  distance_total_nm: z.number(),
  distance_sailed_nm: z.number(),
  fuel_used: z.number(),
  fees_paid: z.number(),
});
export type ActiveVoyage = z.infer<typeof ActiveVoyageSchema>;

export const ShipStateSchema = z.object({
  id: z.string(),
  class_id: z.string(),
  name: z.string(),
  position: GeoPointSchema,
  heading: z.number(),
  speed_knots: z.number(),
  /** 0..1 engine throttle or sail setting. */
  throttle: z.number().min(0).max(1),
  /** -1..1 rudder; negative turns to port (left). */
  rudder: z.number().min(-1).max(1),
  status: ShipStatusSchema,
  docked_port_id: z.string().nullable(),
  /** Fuel tonnes for engine ships, provision days for sailing ships. */
  endurance: z.number(),
  cargo: z.array(CargoItemSchema),
  condition: z.number().min(0).max(100),
  autopilot: z.boolean(),
  route: z.array(WaypointSchema),
  waypoint_index: z.number().int(),
  voyage: ActiveVoyageSchema.nullable(),
  purchased_sim_seconds: z.number(),
  total_distance_nm: z.number(),
});
export type ShipState = z.infer<typeof ShipStateSchema>;

export const PortStateSchema = z.object({
  access: PortAccessSchema,
  infrastructure: z.partialRecord(PortInfrastructureKindSchema, z.number().int()),
  visited: z.boolean(),
  /** Scenario-event or diplomacy driven fee multiplier. */
  fee_multiplier: z.number(),
  influence: z.number().min(0).max(100),
  /** Population in thousands (abstract). Zero means "not yet seeded" for older saves. */
  population: z.number().default(0),
  /** Prosperity 0..100, pulled daily toward a target set by calls, trade, facilities and events. */
  prosperity: z.number().default(0),
  /** Public order 0..100. */
  order: z.number().default(70),
  /** Rival port calls already counted toward prosperity. */
  rival_calls_snapshot: z.number().default(0),
});
export type PortState = z.infer<typeof PortStateSchema>;

export const ContractStatusSchema = z.enum(["available", "accepted", "in_transit", "completed", "failed", "expired"]);
export type ContractStatus = z.infer<typeof ContractStatusSchema>;

export const ContractSchema = z.object({
  id: z.string(),
  origin_port_id: z.string(),
  destination_port_id: z.string(),
  good_id: z.string(),
  quantity: z.number(),
  payment: z.number(),
  estimated_costs: z.number(),
  deadline_sim_seconds: z.number(),
  created_sim_seconds: z.number(),
  distance_nm: z.number(),
  status: ContractStatusSchema,
  assigned_ship_id: z.string().nullable(),
  completed_sim_seconds: z.number().nullable(),
  paid: z.boolean(),
  mission: z.boolean(),
  /** Set when generated by the seeded contract generator. */
  generation_key: z.string().nullable(),
  /** Rival that posted this contract as a charter (it pays on delivery); null for ordinary offers. */
  charterer_id: z.string().nullable().default(null),
});
export type Contract = z.infer<typeof ContractSchema>;

export const LedgerEntrySchema = z.object({
  id: z.string(),
  sim_seconds: z.number(),
  date: GameDateSchema,
  amount: z.number(),
  category: z.enum([
    "contract_payment",
    "contract_bonus",
    "contract_penalty",
    "cargo_sale",
    "cargo_purchase",
    "fuel",
    "provisions",
    "port_fee",
    "maintenance",
    "repair",
    "ship_purchase",
    "ship_sale",
    "infrastructure",
    "technology",
    "diplomacy",
    "objective_reward",
    "income",
    "other",
  ]),
  description: z.string(),
  ship_id: z.string().nullable(),
  port_id: z.string().nullable(),
});
export type LedgerEntry = z.infer<typeof LedgerEntrySchema>;
export type LedgerCategory = LedgerEntry["category"];

export const VoyageRecordSchema = z.object({
  id: z.string(),
  ship_id: z.string(),
  ship_name: z.string(),
  origin_port_id: z.string(),
  destination_port_id: z.string(),
  departed_sim_seconds: z.number(),
  arrived_sim_seconds: z.number(),
  distance_nm: z.number(),
  revenue: z.number(),
  expenses: z.number(),
  bonuses: z.number(),
  penalties: z.number(),
  net: z.number(),
  contracts_completed: z.array(z.string()),
  notes: z.array(z.string()),
});
export type VoyageRecord = z.infer<typeof VoyageRecordSchema>;

export const ObjectiveStateSchema = z.object({
  status: z.enum(["locked", "active", "completed"]),
  completed_sim_seconds: z.number().nullable(),
  rewarded: z.boolean(),
});
export type ObjectiveState = z.infer<typeof ObjectiveStateSchema>;

export const DiplomacyStateSchema = z.object({
  relation: z.number().min(0).max(100),
  agreements: z.array(z.enum(["trade_agreement", "port_access"])),
  last_action_sim_seconds: z.number().nullable(),
});
export type DiplomacyState = z.infer<typeof DiplomacyStateSchema>;

export const MarketEntrySchema = z.object({ price: z.number(), stock: z.number() });

export const RivalShipStatusSchema = z.enum(["docked", "sailing"]);

export const RivalShipSchema = z.object({
  id: z.string(),
  class_id: z.string(),
  name: z.string(),
  position: GeoPointSchema,
  heading: z.number(),
  speed_knots: z.number(),
  status: RivalShipStatusSchema,
  docked_port_id: z.string().nullable(),
  route: z.array(WaypointSchema),
  waypoint_index: z.number().int(),
  /** Nautical miles covered along the current leg. */
  leg_progress_nm: z.number(),
  destination_port_id: z.string().nullable(),
  origin_port_id: z.string().nullable(),
  /** Contract taken from the shared offer board, if any; otherwise the ship trades on its own account. */
  contract_id: z.string().nullable(),
  /** Earnings expected on arrival for an own-account voyage (ballast runs and legacy saves). */
  voyage_value: z.number(),
  /** Goods bought at the origin market to sell at the destination. */
  cargo: z.object({ good_id: z.string(), quantity: z.number(), bought_at: z.number() }).nullable().default(null),
  /** Simulated time at which a docked ship next decides what to do. */
  next_decision_sim_seconds: z.number(),
  total_distance_nm: z.number(),
});
export type RivalShip = z.infer<typeof RivalShipSchema>;

export const RivalStateSchema = z.object({
  id: z.string(),
  treasury: z.number(),
  ships: z.record(z.string(), RivalShipSchema),
  /** Calls made at each port, the basis of market share. */
  port_calls: z.record(z.string(), z.number()),
  /** Facilities the rival has built, by port and level. */
  developed: z.record(z.string(), z.number()),
  /** Standing with the player's house, 0..100. */
  relation: z.number().min(0).max(100),
  partnership: z.boolean(),
  last_relation_action_sim_seconds: z.number().nullable(),
  last_purchase_sim_seconds: z.number(),
  last_development_sim_seconds: z.number(),
  stats: z.object({ deliveries: z.number(), contracts_taken: z.number(), revenue: z.number(), charters_posted: z.number().default(0), goods_sold: z.number().default(0) }),
  /** Standing with each other rival, 0..100 (50 when unknown). */
  relations: z.record(z.string(), z.number()).default({}),
  /** Rivals this one is allied with: no bidding at each other's home ports, preference for each other's charters. */
  allies: z.array(z.string()).default([]),
  last_charter_sim_seconds: z.number().default(0),
  /** How the rival answered historical events, newest first (defaulted for earlier saves). */
  event_log: z.array(z.object({ event_id: z.string(), sim_seconds: z.number(), note: z.string() })).default([]),
});
export type RivalState = z.infer<typeof RivalStateSchema>;

export const NotificationSchema = z.object({
  id: z.string(),
  sim_seconds: z.number(),
  kind: z.enum(["info", "success", "warning", "event", "objective"]),
  title: z.string(),
  message: z.string(),
  read: z.boolean(),
  link: z.string().optional(),
});
export type GameNotification = z.infer<typeof NotificationSchema>;

export const EmpireSchema = z.object({
  name: z.string(),
  /** Historical polity the player operates within, if any. */
  polity_id: z.string().nullable(),
  /** The player's own entity is always a fictional creation unless the scenario says otherwise. */
  is_fictional: z.boolean(),
  emblem: z.object({ symbol: z.string(), color: z.string() }),
  home_port_id: z.string(),
  difficulty: z.enum(["easy", "normal", "hard"]),
  motto: z.string().optional(),
  rules: z.enum(["historical", "sandbox"]),
});
export type Empire = z.infer<typeof EmpireSchema>;

/**
 * Alternate-history sandbox. A "turning point" is a documented event with gameplay effects.
 * In sandbox games history pauses at each one and the player decides whether it happens as
 * documented, is averted, softened or turned around. Everything that departs from the record
 * is logged here and labelled fiction; the historical database itself is never changed.
 */
export const DivergenceChoiceSchema = z.enum(["historical", "averted", "softened", "reversed"]);
export type DivergenceChoice = z.infer<typeof DivergenceChoiceSchema>;

export const DivergenceSchema = z.object({
  event_id: z.string(),
  choice: DivergenceChoiceSchema,
  sim_seconds: z.number(),
  date: GameDateSchema,
  /** What the game did instead of the documented consequence, in plain words. */
  note: z.string(),
});
export type Divergence = z.infer<typeof DivergenceSchema>;

export const AlternateHistorySchema = z.object({
  /** Decisions made or set in advance, by event id. */
  decisions: z.record(z.string(), DivergenceChoiceSchema),
  /** The turning point waiting for a decision; the game stays paused while it is set. */
  pending_event_id: z.string().nullable(),
  /** Every departure from the documented record, in order. */
  divergences: z.array(DivergenceSchema),
});
export type AlternateHistory = z.infer<typeof AlternateHistorySchema>;

export const GameStateSchema = z.object({
  version: z.literal(SAVE_VERSION),
  id: z.string(),
  created_at: z.string(),
  updated_at: z.string(),
  mode: GameModeSchema,
  scenario_id: z.string(),
  empire: EmpireSchema,
  date: GameDateSchema,
  start_date: GameDateSchema,
  sim_seconds: z.number(),
  time_scale: z.number(),
  paused: z.boolean(),
  treasury: z.number(),
  ledger: z.array(LedgerEntrySchema),
  ships: z.record(z.string(), ShipStateSchema),
  active_ship_id: z.string().nullable(),
  ports: z.record(z.string(), PortStateSchema),
  contracts: z.record(z.string(), ContractSchema),
  voyages: z.array(VoyageRecordSchema),
  technologies: z.array(z.string()),
  objectives: z.record(z.string(), ObjectiveStateSchema),
  achievements: z.array(z.string()),
  diplomacy: z.record(z.string(), DiplomacyStateSchema),
  market: z.record(z.string(), z.record(z.string(), MarketEntrySchema)),
  /** AI trading powers. Defaulted so saves from before rivals existed still load. */
  rivals: z.record(z.string(), RivalStateSchema).default({}),
  applied_events: z.array(z.string()),
  /** Sandbox decisions and divergences. Defaulted so earlier saves still load. */
  alternate_history: AlternateHistorySchema.default({ decisions: {}, pending_event_id: null, divergences: [] }),
  notifications: z.array(NotificationSchema),
  tutorial: z.object({ step: z.number().int(), completed: z.boolean(), dismissed: z.boolean() }),
  stats: z.object({
    contracts_completed: z.number(),
    distance_sailed_nm: z.number(),
    total_revenue: z.number(),
    total_expenses: z.number(),
    goods_delivered: z.record(z.string(), z.number()),
    last_maintenance_day: z.number(),
  }),
  campaign: z.object({
    status: z.enum(["active", "victory", "historical_end", "defeat"]),
    ended_sim_seconds: z.number().nullable(),
    end_note: z.string().nullable(),
  }),
  seed: z.number(),
  /** Pending voyage report to show the player once. */
  pending_report: VoyageRecordSchema.nullable(),
  settings: z.object({ autosave: z.boolean() }),
});
export type GameState = z.infer<typeof GameStateSchema>;

export type { GameDate };

export const SaveSummarySchema = z.object({
  id: z.string(),
  scenario_id: z.string(),
  mode: GameModeSchema,
  empire_name: z.string(),
  treasury: z.number(),
  currency_symbol: z.string(),
  date: GameDateSchema,
  ships: z.number().int(),
  contracts_completed: z.number().int(),
  updated_at: z.string(),
  campaign_status: z.string(),
});
export type SaveSummary = z.infer<typeof SaveSummarySchema>;
